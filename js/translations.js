// Zahlen im Titel an die Zielsprache anpassen (0.9 -> 0,9 in DE).
export function localizeDecimal(text, lang){
  return String(text).replace(/(\d)\.(\d)/g, (m, a, b) => lang === "de" ? `${a},${b}` : `${a}.${b}`);
}

// Zwei Stufen: Satzmuster zuerst, danach einzelne Woerter.
export function translateFeedTitle(rawTitle, lang){
  const clean = cleanFeedText(rawTitle);
  if(!clean || lang === "en" || !FEED_I18N[lang]) return clean;
  let out = localizeDecimal(clean, lang);
  for(const [pattern, template] of FEED_I18N[lang].phrases){
    out = out.replace(pattern, template);
  }
  // Nur Leerraum auffangen, der zwischen zwei Wörtern entstanden ist.
  // Der Abstand vor einem Gedankenstrich gehört zum Text und bleibt stehen.
  return out
    .replace(/\s+([,.;:!?])/g, "$1")
    .replace(/\s{2,}/g, " ")
    .replace(/\s+—/g, " —")
    .trim();
}

// Sichtbare Regionen uebersetzen.
export function localizeRegions(text, lang){
  const map = FEED_I18N[lang]?.regions;
  if(!map) return text;
  let out = String(text);
  for(const [needle, replacement] of Object.entries(map)){
    out = out.replace(new RegExp(`\\b${needle.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}\\b`, "gi"), replacement);
  }
  return out;
}

// Aus dem englischen Fliesstext die eigentlichen Messdaten ziehen. Die
// Zahlen bleiben unveraendert, nur die Bezeichnungen kommen aus der
// aktuell gewaehlten Sprache.
export function extractFeedFacts(description){
  const text = String(description || "");
  const facts = {};
  const push = (key, value) => { if(value && facts[key] === undefined) facts[key] = value; };

  // Eigene Zahlform statt [0-9.,]+ - sonst schluckt der Treffer das
  // Satzzeichen mit ("21.9," statt "21.9").
  let m = text.match(/passing at\s+(\d+(?:[.,]\d+)?)\s+lunar distances/i);
  if(m) push("moonDistances", m[1]);
  m = text.match(/\(([\d.,]*\d)\s*km\)/i);
  if(m) push("distanceKm", m[1]);
  m = text.match(/absolute magnitude \(H\) of\s+(\d+(?:[.,]\d+)?)/i);
  if(m) push("magnitude", m[1]);
  m = text.match(/diameter of roughly\s+(\d+(?:[.,]\d+)?)\s*m/i);
  if(m) push("diameterM", m[1]);
  m = text.match(/flyby velocity of\s+(\d+(?:[.,]\d+)?)\s*km\/s/i);
  if(m) push("velocity", m[1]);
  m = text.match(/Visible from:\s*([^\n.]+)/i);
  if(m) push("visibleFrom", m[1].trim());
  return facts;
}

