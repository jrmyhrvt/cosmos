export function cleanFeedText(value){
  return String(value || '')
    // Strip emoji and symbol glyphs from live feed titles; COSMOS uses its own pictograms.
    .replace(/[\u{1F000}-\u{1FAFF}\u{2600}-\u{27BF}]/gu, '')
    .replace(/[\uFE0F\u200D]/g, '')
    .replace(/\s{2,}/g, ' ')
    .replace(/^[-–—:|·\s]+|[-–—:|·\s]+$/g, '')
    .trim();
}

